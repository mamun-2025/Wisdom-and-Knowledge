

# 1. What is Finance?
"""
Finance is the study and the managemnet of money, investments, financial resources, and financial activities.
Finance হলো অর্থ, বিনিয়োগ, আর্থিক সম্পদ এবং আর্থিক কার্যক্রম কীভাবে অর্জন, পরিচালনা, সঞ্চয়, ব্যবহার ও বৃদ্ধি করতে হয় তার অধ্যয়ন।

সহজভাবে বললে:
তুমি টাকা কোথা থেকে উপার্জন করবে, কীভাবে খরচ করবে, কতটুকু সঞ্চয় করবে, কোথায় বিনিয়োগ করবে 
এবং ভবিষ্যতের আর্থিক নিরাপত্তা কীভাবে নিশ্চিত করবে—এসব বিষয় Finance-এর অন্তর্ভুক্ত।
"""


# 2. Important Financial Terminology
"""
আর্থিক ব্যবস্থাপনা = Finance
অর্থ = Money
আয় = Income
ব্যয় = Expense
সঞ্চয় = Savings
বিনিয়োগ = Investment
বাজেট = Budget
সম্পদ = Asset
দায় = Liability
মুনাফা = Profit
ক্ষতি = Loss
ঋণ = Debt
সম্পদ বা আর্থিক সমৃদ্ধি = Wealth 
মূলধন = Capital
নগদ অর্থের প্রবাহ = Cash Flow

মনে রাখবে:
Income ≠ Wealth
Income হলো নির্দিষ্ট সময়ে তোমার উপার্জিত অর্থ।

Wealth হলো তোমার মালিকানাধীন সম্পদ ও দায়ের পার্থক্যের মাধ্যমে নির্ধারিত নিট আর্থিক অবস্থান।

উদাহরণ:
কোনো ব্যক্তি মাসে ১ লাখ টাকা আয় করলেও তার ঋণ ও খরচ অনেক বেশি হতে পারে। 
অন্যদিকে, মাসে ৩০ হাজার টাকা আয় করা কোনো ব্যক্তি নিয়মিত সঞ্চয় করে ভালো সম্পদ গড়ে তুলতে পারেন।

"""


