# Part 2 — Understanding Number Properties
# 5. Even & Odd Numbers (জোড় ও বিজোড় সংখ্যা)
"""
Even Number (জোড় সংখ্যা)
যে সংখ্যাকে 2 দিয়ে ভাগ করলে কোনো ভাগশেষ থাকে না, তাকে Even Number বলে।

Examples:
2,4,6,8,10,12,14,16,...

উদাহরণ:

১২টি আম দুইজনের মধ্যে সমানভাবে ভাগ করলে প্রত্যেকে ৬টি করে পাবে।
12 / 2 = 6

তাই 12 একটি Even Number।
Odd Number (বিজোড় সংখ্যা)
যে সংখ্যাকে 2 দিয়ে ভাগ করলে ভাগশেষ 1 থাকে, তাকে Odd Number বলে।

Examples:
1,3,5,7,9,11,13,15,..

উদাহরণ:

৫টি কলা দুইজনের মধ্যে সমানভাবে ভাগ করলে প্রত্যেকে ২টি করে পাবে এবং ১টি অবশিষ্ট থাকবে।
5 / 2 = 1 

তাই 5 একটি Odd Number।

দ্রুত চেনার কৌশল
শুধু শেষ Digit দেখলেই হবে।

শেষ Digit	Number Type
0, 2, 4, 6, 8 = Even
1, 3, 5, 7, 9 =Odd

উদাহরণ:
- 1,248 → Even
- 3,567 → Odd
- 9,990 → Even
- 7,351 → Odd

"""


