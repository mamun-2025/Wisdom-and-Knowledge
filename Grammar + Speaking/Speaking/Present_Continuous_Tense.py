

# 1. What is Present Continuous Tense?
"""
Present Continuous Tense হলো এমন একটি Tense, যা দিয়ে সাধারণত বোঝায় কোনো কাজ এখন চলছে, বর্তমানে চলমান রয়েছে অথবা কোনো পরিবর্তন ঘটছে।

Structure: Subject + am/is/are + Verb(-ing)
            I am studying.
            He is working.
            She is cooking.
            It is raining.
            We are learning.
            You are speaking.
            They are playing.

মনে রাখবে:
I = am 
He/She/It = is
We/You/They = are 

"""

# 2. Verb + ing কীভাবে তৈরি হয়?
"""
Work = Working
Read = Reading
Play = Playing
Learn = Learning
Study = Studying
Cook = Cooking
Write = Writing
Make = Making
Run = Running
Sit = Sitting
Swim = Swimming
Lie = Lying

কিছু গুরুত্বপূর্ণ Spelling Rules:
1. সাধারণত Verb-এর শেষে ing যোগ হয়: Work → Working।
2. শেষে e থাকলে অনেক সময় e বাদ যায়: Make → Making।
3. কিছু ছোট Verb-এর শেষের consonant দ্বিগুণ হয়: Run → Running।
4. ie থাকলে y হয়: Lie → Lying।

"""

